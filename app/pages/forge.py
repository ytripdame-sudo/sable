"""Forge page: output format and the archive name.

Two choices, one of which has a consequence worth showing. ``exe`` needs a frozen
launcher, so the page says where the launcher comes from and refuses to pretend the
build will work without one; ``py`` ignores ballast, so the note says so rather than
letting the tuning page's number look like it did something.

The launcher field fills itself in when this tree has one: ``tools/dist`` is where the
spec file puts it, and a path that no longer exists is not remembered just because it
was once typed. One launcher opens every artifact, so the field is a path to a file and
not a per-build setting.

The preview is generated by ``core.rename.generate`` — the same function that names the
finished artifact — so what the page shows is what the build produces, not a second
implementation of the same idea. A name typed by hand is previewed as typed. It sits in
its own block because the filename is the one thing on this page a reader will copy out
of the window.
"""

from __future__ import annotations

from pathlib import Path
from typing import Final

from PySide6.QtCore import QSettings, Qt
from PySide6.QtWidgets import QComboBox, QHBoxLayout, QLabel, QVBoxLayout, QWidget

from core import rename
from core.forge import OUTPUT_EXE, OUTPUT_MODES, OUTPUT_PY

from ..widgets.field import Card, LabelledEdit

__all__ = ["ForgePage"]

_STUB_KEY: Final[str] = "form/stub"

_REPO_ROOT: Final[Path] = Path(__file__).resolve().parents[2]
_DEFAULT_STUB: Final[Path] = _REPO_ROOT / "tools" / "dist" / "sable-launcher.exe"

_NOTES: Final[dict[str, str]] = {
    OUTPUT_EXE: "Frozen launcher plus the sealed payload. A launcher is required and ballast applies.",
    OUTPUT_PY: "One runnable script. Ballast is ignored because padding text changes nothing.",
}


def default_stub() -> Path | None:
    """The launcher ``tools/sable-launcher.spec`` produces, once it has been built."""
    return _DEFAULT_STUB if _DEFAULT_STUB.is_file() else None


class ForgePage(QWidget):
    """Format selector, optional name, live preview."""

    title: Final[str] = "Forge"
    description: Final[str] = "What shape the finished artifact takes."

    def __init__(self, parent: QWidget | None = None) -> None:
        super().__init__(parent)

        self._mode = QComboBox()
        self._mode.setObjectName("outputMode")
        self._mode.setFixedWidth(220)
        for mode in OUTPUT_MODES:
            self._mode.addItem(mode, mode)
        self._mode.currentIndexChanged.connect(self._on_mode)

        mode_label = QLabel("Format")
        mode_label.setObjectName("fieldLabel")

        mode_row = QHBoxLayout()
        mode_row.setContentsMargins(0, 0, 0, 0)
        mode_row.setSpacing(12)
        mode_row.addWidget(self._mode, 0)
        mode_row.addStretch(1)

        self._note = QLabel(_NOTES[OUTPUT_EXE])
        self._note.setObjectName("hint")
        self._note.setWordWrap(True)

        self._name = LabelledEdit("Name", placeholder="leave blank to generate")
        self._name.changed.connect(self._refresh_preview)

        self._preview = QLabel("")
        self._preview.setObjectName("preview")
        self._preview.setWordWrap(True)
        self._preview.setAlignment(Qt.AlignmentFlag.AlignLeft | Qt.AlignmentFlag.AlignVCenter)

        preview_label = QLabel("Will be written as")
        preview_label.setObjectName("fieldLabel")

        format_card = Card(
            "Format",
            "The script is a single file and needs nothing beside it. The executable "
            "is the frozen launcher with the sealed payload welded on.",
        )
        format_card.body.addWidget(mode_label)
        format_card.add_row(mode_row)
        format_card.body.addWidget(self._note)
        format_card.add(self._name)
        format_card.body.addWidget(preview_label)
        format_card.add(self._preview)

        self._stub = LabelledEdit(
            "Frozen launcher", placeholder="tools/dist/sable-launcher.exe", browse=True
        )
        self._stub.set_text(self._remembered_stub())
        self._stub.changed.connect(self._remember_stub)

        stub_hint = QLabel(
            "Built once from tools/sable-launcher.spec and reused by every artifact. "
            "One launcher opens every build, because the key travels in the trailer "
            "rather than in the stub."
        )
        stub_hint.setObjectName("hint")
        stub_hint.setWordWrap(True)

        launcher_card = Card(
            "Launcher",
            "Only used by the executable format.",
        )
        launcher_card.add(self._stub)
        launcher_card.body.addWidget(stub_hint)

        column = QVBoxLayout(self)
        column.setContentsMargins(0, 0, 0, 0)
        column.setSpacing(18)
        column.addWidget(format_card)
        column.addWidget(launcher_card)
        column.addStretch(1)

        self._refresh_preview()

    # --- value ---------------------------------------------------------------

    def mode(self) -> str:
        return str(self._mode.currentData())

    def name(self) -> str | None:
        text = self._name.text().strip()
        return text or None

    def stub(self) -> Path | None:
        return self._stub.path()

    def values(self) -> dict[str, object]:
        return {"mode": self.mode(), "name": self.name(), "stub": self.stub()}

    def reset(self) -> None:
        self._mode.setCurrentIndex(0)
        self._name.set_text("")
        self._name.clear_problem()
        self._stub.clear_problem()
        self._refresh_preview()

    # --- state ---------------------------------------------------------------

    def show_problems(self, problems) -> None:
        for problem in problems:
            if problem.path == "output.name":
                self._name.set_problem(problem.message)
            elif problem.path == "output.stub":
                self._stub.set_problem(problem.message)

    # --- internals -----------------------------------------------------------

    def _on_mode(self, _index: int) -> None:
        mode = self.mode()
        self._note.setText(_NOTES.get(mode, ""))
        self._stub.setEnabled(mode == OUTPUT_EXE)
        self._refresh_preview()

    def _refresh_preview(self, _text: str = "") -> None:
        mode = self.mode()
        extension = ".exe" if mode == OUTPUT_EXE else ".py"
        typed = self.name()
        if typed is None:
            try:
                preview = rename.generate(extension)
            except rename.RenameError as exc:
                self._preview.setText(f"cannot generate a name ({exc})")
                return
            self._preview.setText(f"Will be named  {preview}")
            return

        try:
            cleaned = rename.sanitize(typed)
        except rename.RenameError as exc:
            self._preview.setText(f"{typed}  is not usable ({exc})")
            return
        if not Path(cleaned).suffix:
            cleaned += extension
        self._preview.setText(f"Will be named  {cleaned}")

    def _remember_stub(self, value: str) -> None:
        settings = QSettings()
        settings.setValue(_STUB_KEY, value)

    def _remembered_stub(self) -> str:
        """A stored launcher that still exists, otherwise the one this tree built."""
        stored = str(QSettings().value(_STUB_KEY, "") or "").strip()
        if stored and Path(stored).is_file():
            return stored
        found = default_stub()
        return str(found) if found is not None else ""
