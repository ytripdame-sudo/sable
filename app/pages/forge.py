"""Forge page: output format, the archive name, the icon and the bound file.

Two choices, one of which has a consequence worth showing. ``exe`` needs a frozen
launcher, so the page says where the launcher comes from and refuses to pretend the
build will work without one; ``py`` ignores ballast, so the note says so rather than
letting the tuning page's number look like it did something.

The launcher field fills itself in when this tree has one: ``tools/dist`` is where the
spec file puts it, and a path that no longer exists is not remembered just because it
was once typed. One launcher opens every artifact, so the field is a path to a file and
not a per-build setting.

The icon and the bound file are the same kind of value: files on this machine that
travel inside the artifact, never fields in ``cfg.json``. The icon patches the launcher
on the copy being written, so it is disabled for script output where there is nothing to
patch. The bound file goes into the payload archive itself, so it applies to both
formats.

The preview is generated by ``core.rename.generate`` — the same function that names the
finished artifact — so what the page shows is what the build produces, not a second
implementation of the same idea. A name typed by hand is previewed as typed. It sits in
its own block because the filename is the one thing on this page a reader will copy out
of the window.
"""

from __future__ import annotations

from pathlib import Path
from typing import Final

from PySide6.QtCore import QSettings, Qt
from PySide6.QtWidgets import QComboBox, QHBoxLayout, QLabel, QVBoxLayout, QWidget

from core import rename
from core.forge import OUTPUT_EXE, OUTPUT_MODES, OUTPUT_PY
from core.schema import VersionConfig

from ..widgets.field import Card, LabelledEdit

__all__ = ["ForgePage"]

_STUB_KEY: Final[str] = "form/stub"
_ICON_KEY: Final[str] = "form/icon"
_FUSE_KEY: Final[str] = "form/fuse"

_REPO_ROOT: Final[Path] = Path(__file__).resolve().parents[2]
_DEFAULT_STUB: Final[Path] = _REPO_ROOT / "tools" / "dist" / "sable-launcher.exe"

_NOTES: Final[dict[str, str]] = {
    OUTPUT_EXE: "Frozen launcher plus the sealed payload. A launcher is required and ballast applies.",
    OUTPUT_PY: "One runnable script. Ballast is ignored because padding text changes nothing.",
}


def default_stub() -> Path | None:
    """The launcher ``tools/sable-launcher.spec`` produces, once it has been built."""
    return _DEFAULT_STUB if _DEFAULT_STUB.is_file() else None


class ForgePage(QWidget):
    """Format selector, optional name, live preview."""

    title: Final[str] = "Forge"
    description: Final[str] = "What shape the finished artifact takes."

    def __init__(self, parent: QWidget | None = None) -> None:
        super().__init__(parent)

        self._mode = QComboBox()
        self._mode.setObjectName("outputMode")
        self._mode.setFixedWidth(220)
        for mode in OUTPUT_MODES:
            self._mode.addItem(mode, mode)
        self._mode.currentIndexChanged.connect(self._on_mode)

        mode_label = QLabel("Format")
        mode_label.setObjectName("fieldLabel")

        mode_row = QHBoxLayout()
        mode_row.setContentsMargins(0, 0, 0, 0)
        mode_row.setSpacing(12)
        mode_row.addWidget(self._mode, 0)
        mode_row.addStretch(1)

        self._note = QLabel(_NOTES[OUTPUT_EXE])
        self._note.setObjectName("hint")
        self._note.setWordWrap(True)

        self._name = LabelledEdit("Name", placeholder="leave blank to generate")
        self._name.changed.connect(self._refresh_preview)

        self._preview = QLabel("")
        self._preview.setObjectName("preview")
        self._preview.setWordWrap(True)
        self._preview.setAlignment(Qt.AlignmentFlag.AlignLeft | Qt.AlignmentFlag.AlignVCenter)

        preview_label = QLabel("Will be written as")
        preview_label.setObjectName("fieldLabel")

        format_card = Card(
            "Format",
            "The script is a single file and needs nothing beside it. The executable "
            "is the frozen launcher with the sealed payload welded on.",
        )
        format_card.body.addWidget(mode_label)
        format_card.add_row(mode_row)
        format_card.body.addWidget(self._note)
        format_card.add(self._name)
        format_card.body.addWidget(preview_label)
        format_card.add(self._preview)

        self._stub = LabelledEdit(
            "Frozen launcher", placeholder="tools/dist/sable-launcher.exe", browse=True
        )
        self._stub.set_text(self._remembered_stub())
        self._stub.changed.connect(self._remember_stub)

        stub_hint = QLabel(
            "Built once from tools/sable-launcher.spec and reused by every artifact. "
            "One launcher opens every build, because the key travels in the trailer "
            "rather than in the stub."
        )
        stub_hint.setObjectName("hint")
        stub_hint.setWordWrap(True)

        # The icon patches the launcher's resources on the copy being written. Nothing
        # is refrozen: the same launcher still opens every build, and only this artifact
        # carries this icon.
        self._icon = LabelledEdit(
            "Icon",
            placeholder="leave blank for the launcher's own",
            browse=True,
            filters="Icons (*.ico)",
        )
        self._icon.set_text(self._remembered(_ICON_KEY))
        self._icon.changed.connect(lambda value: self._remember(_ICON_KEY, value))

        icon_hint = QLabel(
            "A .ico patched into the executable's resources at build time. The "
            "launcher is not rebuilt, so this costs one resource write per artifact "
            "and nothing else. Script output has no icon slot."
        )
        icon_hint.setObjectName("hint")
        icon_hint.setWordWrap(True)

        launcher_card = Card(
            "Launcher",
            "Only used by the executable format.",
        )
        launcher_card.add(self._stub)
        launcher_card.body.addWidget(stub_hint)
        launcher_card.add(self._icon)
        launcher_card.body.addWidget(icon_hint)

        # The bound file travels inside the archive itself, so it works in both modes.
        self._fuse = LabelledEdit(
            "Bound file",
            placeholder="one file, started when the artifact runs",
            browse=True,
            filters="Programs (*.exe *.com *.scr);;All files (*)",
        )
        self._fuse.set_text(self._remembered(_FUSE_KEY))
        self._fuse.changed.connect(lambda value: self._remember(_FUSE_KEY, value))

        fuse_hint = QLabel(
            "Welded into the payload archive and extracted to a folder of its own when "
            "the artifact runs. The executable is started detached, before collection, "
            "and everything beside it is extracted but left alone. One file, ceiling "
            "64 MB."
        )
        fuse_hint.setObjectName("hint")
        fuse_hint.setWordWrap(True)

        bound_card = Card(
            "Bound file",
            "Carried inside the archive rather than beside it.",
        )
        bound_card.add(self._fuse)
        bound_card.body.addWidget(fuse_hint)

        # The properties sheet and the dialog are one idea with two surfaces: what the
        # file looks like while it is being looked at. Both are written into the
        # launcher's resources, both are optional, and both are empty by default.
        self._company = LabelledEdit("Company", placeholder="leave blank to keep the launcher's")
        self._product = LabelledEdit("Product", placeholder="leave blank to keep the launcher's")
        self._description = LabelledEdit(
            "Description", placeholder="shown beside the process name"
        )
        self._copyright = LabelledEdit("Copyright", placeholder="optional")
        self._original_name = LabelledEdit(
            "Original filename", placeholder="the name the file claims to have been"
        )
        self._file_version = LabelledEdit("File version", placeholder="1.0.0.0")
        self._product_version = LabelledEdit(
            "Product version", placeholder="blank copies the file version"
        )

        version_hint = QLabel(
            "Written into RT_VERSION, which is the block the properties sheet reads. "
            "Versions are four numbers, each 0 to 65535. A field left blank is left out "
            "of the block rather than written empty."
        )
        version_hint.setObjectName("hint")
        version_hint.setWordWrap(True)

        disguise_card = Card(
            "Disguise",
            "What the file says about itself when someone looks. Empty means the "
            "launcher's own values are left alone.",
        )
        for field in (
            self._company,
            self._product,
            self._description,
            self._copyright,
            self._original_name,
            self._file_version,
            self._product_version,
        ):
            disguise_card.add(field)
            field.changed.connect(self._refresh_preview)
        disguise_card.body.addWidget(version_hint)

        self._decoy_seconds = LabelledEdit(
            "Dialog seconds", placeholder="0 for no dialog"
        )
        self._decoy_title = LabelledEdit("Dialog title", placeholder="Setup")
        self._decoy_text = LabelledEdit("Dialog text", placeholder="Preparing, please wait…")
        for field in (self._decoy_seconds, self._decoy_title, self._decoy_text):
            disguise_card.add(field)
        self._decoy_seconds.changed.connect(self._refresh_preview)

        decoy_hint = QLabel(
            "One dialog, on screen for that many seconds, closed by a timer rather than "
            "by a click. It runs on its own thread: a dialog that nobody dismisses must "
            "never hold up the run. Ceiling 600 seconds."
        )
        decoy_hint.setObjectName("hint")
        decoy_hint.setWordWrap(True)
        disguise_card.body.addWidget(decoy_hint)

        column = QVBoxLayout(self)
        column.setContentsMargins(0, 0, 0, 0)
        column.setSpacing(18)
        column.addWidget(format_card)
        column.addWidget(launcher_card)
        column.addWidget(bound_card)
        column.addWidget(disguise_card)
        column.addStretch(1)

        self._on_mode(0)

    # --- value ---------------------------------------------------------------

    def mode(self) -> str:
        return str(self._mode.currentData())

    def name(self) -> str | None:
        text = self._name.text().strip()
        return text or None

    def stub(self) -> Path | None:
        return self._stub.path()

    def icon(self) -> Path | None:
        return self._icon.path()

    def fuse(self) -> Path | None:
        return self._fuse.path()

    def version(self) -> VersionConfig:
        """The properties sheet, with blank fields meaning "leave it alone"."""
        return VersionConfig(
            company=self._company.text().strip(),
            product=self._product.text().strip(),
            description=self._description.text().strip(),
            copyright=self._copyright.text().strip(),
            original_name=self._original_name.text().strip(),
            file_version=self._file_version.text().strip(),
            product_version=self._product_version.text().strip(),
        )

    def decoy(self) -> tuple[int, str, str]:
        """``(seconds, title, text)``. An unparseable number is zero, not a crash."""
        raw = self._decoy_seconds.text().strip()
        try:
            seconds = int(raw) if raw else 0
        except ValueError:
            seconds = -1
        return (
            seconds,
            self._decoy_title.text().strip(),
            self._decoy_text.text().strip(),
        )

    def values(self) -> dict[str, object]:
        seconds, title, text = self.decoy()
        return {
            "mode": self.mode(),
            "name": self.name(),
            "stub": self.stub(),
            "icon": self.icon(),
            "fuse": self.fuse(),
            "version": self.version(),
            "decoy_seconds": seconds,
            "decoy_title": title,
            "decoy_text": text,
        }

    def reset(self) -> None:
        self._mode.setCurrentIndex(0)
        self._name.set_text("")
        self._name.clear_problem()
        self._stub.clear_problem()
        self._icon.clear_problem()
        self._fuse.clear_problem()
        for field in (
            self._company,
            self._product,
            self._description,
            self._copyright,
            self._original_name,
            self._file_version,
            self._product_version,
            self._decoy_seconds,
            self._decoy_title,
            self._decoy_text,
        ):
            field.set_text("")
            field.clear_problem()
        self._refresh_preview()

    # --- state ---------------------------------------------------------------

    def show_problems(self, problems) -> None:
        prefixes: tuple[tuple[str, LabelledEdit], ...] = (
            ("output.version.company", self._company),
            ("output.version.product", self._product),
            ("output.version.description", self._description),
            ("output.version.copyright", self._copyright),
            ("output.version.original_name", self._original_name),
            ("output.version.file_version", self._file_version),
            ("output.version.product_version", self._product_version),
            ("output.decoy.seconds", self._decoy_seconds),
            ("output.decoy.title", self._decoy_title),
            ("output.decoy.text", self._decoy_text),
        )
        for problem in problems:
            if problem.path == "output.name":
                self._name.set_problem(problem.message)
            elif problem.path == "output.stub":
                self._stub.set_problem(problem.message)
            elif problem.path == "output.icon":
                self._icon.set_problem(problem.message)
            elif problem.path == "output.fuse":
                self._fuse.set_problem(problem.message)
            else:
                for path, field in prefixes:
                    if problem.path == path:
                        field.set_problem(problem.message)
                        break

    # --- internals -----------------------------------------------------------

    def _on_mode(self, _index: int) -> None:
        mode = self.mode()
        self._note.setText(_NOTES.get(mode, ""))
        self._stub.setEnabled(mode == OUTPUT_EXE)
        self._icon.setEnabled(mode == OUTPUT_EXE)
        self._refresh_preview()

    def _refresh_preview(self, _text: str = "") -> None:
        mode = self.mode()
        extension = ".exe" if mode == OUTPUT_EXE else ".py"
        typed = self.name()
        if typed is None:
            # Same order the pipeline uses: a bound file lends its name, and only a
            # build with nothing to take a name from invents one.
            bound = self.fuse()
            try:
                if bound is not None:
                    preview = rename.derive(bound.name, extension)
                else:
                    preview = rename.generate(extension)
            except rename.RenameError as exc:
                self._preview.setText(f"cannot name the artifact ({exc})")
                return
            source = " (from the bound file)" if bound is not None else ""
            self._preview.setText(f"Will be named  {preview}{source}")
            return

        try:
            cleaned = rename.sanitize(typed)
        except rename.RenameError as exc:
            self._preview.setText(f"{typed}  is not usable ({exc})")
            return
        if not Path(cleaned).suffix:
            cleaned += extension
        self._preview.setText(f"Will be named  {cleaned}")

    def _remember(self, key: str, value: str) -> None:
        QSettings().setValue(key, value)

    def _remembered(self, key: str) -> str:
        """A stored path, but only while the file is still there."""
        stored = str(QSettings().value(key, "") or "").strip()
        return stored if stored and Path(stored).is_file() else ""

    def _remember_stub(self, value: str) -> None:
        self._remember(_STUB_KEY, value)

    def _remembered_stub(self) -> str:
        """A stored launcher that still exists, otherwise the one this tree built."""
        stored = self._remembered(_STUB_KEY)
        if stored:
            return stored
        found = default_stub()
        return str(found) if found is not None else ""
